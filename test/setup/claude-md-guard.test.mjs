// claude-md-guard.test.mjs — keeps .claude/CLAUDE.md hand-owned (D-04/D-05).
// GSD's generate-claude-md skips a file with no section markers, but rewrites marked
// sections from .planning/research/STACK.md — which once shipped wrong versions to
// every fork. So: no GSD markers, and no regrown stack/version tables. Versions live
// in package.json only.
//
// Runs in the plain-node `setup` project (include glob: test/setup/**/*.test.mjs).
import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const text = readFileSync(
  fileURLToPath(new URL('../../.claude/CLAUDE.md', import.meta.url)),
  'utf8'
)

const derivableHeadings = [
  'Technology Stack',
  'Recommended Stack',
  'Core Technologies',
  'Supporting Libraries',
  'Development Tools',
  'Version Compatibility',
  'Installation',
  'Sources',
  'Integration-API Module',
  'How It Fits Together',
]

// GSD's empty-section placeholders (dropped in 25-07): headings and their filler phrases.
const placeholderHeadings = ['Stack Patterns by Variant', 'Conventions', 'Architecture', 'Project Skills', 'Developer Profile']
const placeholderPhrases = ['not yet established', 'not yet mapped', 'No project skills found', 'Profile not yet configured']
const placeholders = (md) => [
  ...(md.match(new RegExp(`^#{2,3} (${placeholderHeadings.join('|')})[ \\t]*$`, 'gm')) ?? []),
  ...placeholderPhrases.filter((p) => md.includes(p)),
]

describe('.claude/CLAUDE.md stays hand-owned (D-04/D-05)', () => {
  it('has no GSD section markers', () => {
    expect(
      text.match(/<!--\s*GSD:.*$/gm) ?? [],
      'Delete the GSD marker comments: a marked section gets regenerated by generate-claude-md'
    ).toEqual([])
  })

  it('does not regrow derivable stack/version sections', () => {
    const re = new RegExp(`^#{2,3} (${derivableHeadings.join('|')}).*$`, 'gm')
    expect(
      text.match(re) ?? [],
      'Delete the derivable section: take versions from package.json, not CLAUDE.md'
    ).toEqual([])
  })

  it('has no GSD placeholder sections', () => {
    expect(placeholders(text), 'Delete the placeholder section: CLAUDE.md holds rationale only').toEqual([])
  })

  it('fixture: the pre-trim placeholder text is flagged', () => {
    const old = [
      '## Conventions',
      'Conventions not yet established. Will populate as patterns emerge during development.',
      '## Architecture',
      'Architecture not yet mapped. Follow existing patterns found in the codebase.',
      '## Project Skills',
      'No project skills found. Add skills to any of: `.claude/skills/`.',
      '## Developer Profile',
      '> Profile not yet configured. Run `/gsd-profile-user` to generate your developer profile.',
      '## Stack Patterns by Variant',
    ].join('\n')
    expect(placeholders(old)).toHaveLength(9)
  })
})
